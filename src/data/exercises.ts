export const exerciseBySlug = Object.fromEntries(exercises.map((e) => [e.slug, e]));

export function exercisesByMuscle(muscleId: string): Exercise[] {
  if (muscleId === "all") return exercises;
  return exercises.filter(
    (e) => e.primary.includes(muscleId) || e.secondary.includes(muscleId),
  );
}

export function findExerciseByName(name: string): Exercise | undefined {
  return exercises.find((e) => e.name === name || e.name.includes(name) || name.includes(e.name));
}
